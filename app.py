@app.route("/scan", methods=["POST"])
def process_scan():
    data = request.get_json(silent=True) or {}
    token = str(data.get("token", "")).strip()

    if not token:
        return jsonify(
            success=False,
            message="No QR token received.",
        ), 400

    connection = get_db_connection()

    try:
        visitor = db_execute(
            connection,
            "SELECT id, full_name FROM visitors WHERE qr_token = ?",
            (token,),
        ).fetchone()

        if visitor is None:
            return jsonify(
                success=False,
                message="Unknown QR code. Register the visitor first.",
            ), 404

        open_visit = db_execute(
            connection,
            """
            SELECT id
            FROM attendance
            WHERE visitor_id = ? AND check_out IS NULL
            ORDER BY id DESC
            LIMIT 1
            """,
            (visitor["id"],),
        ).fetchone()

        if open_visit:
            db_execute(
                connection,
                """
                UPDATE attendance
                SET check_out = CURRENT_TIMESTAMP
                WHERE id = ?
                """,
                (open_visit["id"],),
            )

            action = "check-out"
            message = (
                f"CHECK-OUT recorded for {visitor['full_name']} "
                f"(Visitor ID {visitor['id']})."
            )

        else:
            db_execute(
                connection,
                """
                INSERT INTO attendance (visitor_id)
                VALUES (?)
                """,
                (visitor["id"],),
            )

            action = "check-in"
            message = (
                f"CHECK-IN recorded for {visitor['full_name']} "
                f"(Visitor ID {visitor['id']})."
            )

        connection.commit()

        return jsonify(
            success=True,
            message=message,
            action=action,
            visitor_id=visitor["id"],
        )

    except Exception:
        connection.rollback()
        app.logger.exception("Error processing QR scan")

        return jsonify(
            success=False,
            message="Could not save attendance. Check the application logs.",
        ), 500

    finally:
        connection.close()


