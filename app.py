def get_db_connection():
    """Use PostgreSQL on Render and SQLite locally."""
    if DATABASE_URL:
        database_url = DATABASE_URL

        # Normalize Render's PostgreSQL URL if needed.
        if database_url.startswith("postgres://"):
            database_url = database_url.replace(
                "postgres://",
                "postgresql://",
                1,
            )

        return psycopg.connect(
            database_url,
            row_factory=dict_row,
            connect_timeout=10,
        )

    connection = sqlite3.connect(DATABASE, timeout=10)
    connection.row_factory = sqlite3.Row
    return connection


def db_execute(connection, query, params=()):
    """Execute SQL using the correct placeholder syntax."""
    if DATABASE_URL:
        query = query.replace("?", "%s")

    return connection.execute(query, params)


def create_qr_for_visitor(visitor_id, token):
    filepath = os.path.join(
        QR_FOLDER,
        f"visitor_{visitor_id}.png",
    )

    qr = qrcode.QRCode(
        version=1,
        box_size=10,
        border=4,
    )

    qr.add_data(token)
    qr.make(fit=True)

    image = qr.make_image(
        fill_color="black",
        back_color="white",
    )
    image.save(filepath)


def initialize_database():
    connection = get_db_connection()

    try:
        if DATABASE_URL:
            # PostgreSQL: Render
            connection.execute("""
                CREATE TABLE IF NOT EXISTS visitors (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    full_name TEXT NOT NULL,
                    contact_number TEXT NOT NULL,
                    purpose TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    qr_token TEXT
                )
            """)

            connection.execute("""
                ALTER TABLE visitors
                ADD COLUMN IF NOT EXISTS qr_token TEXT
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS attendance (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    visitor_id INTEGER NOT NULL REFERENCES visitors(id),
                    check_in TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    check_out TIMESTAMP
                )
            """)

        else:
            # SQLite: Local computer
            connection.execute("""
                CREATE TABLE IF NOT EXISTS visitors (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    full_name TEXT NOT NULL,
                    contact_number TEXT NOT NULL,
                    purpose TEXT NOT NULL,
                    created_at TEXT DEFAULT CURRENT_TIMESTAMP,
                    qr_token TEXT
                )
            """)

            columns = {
                row["name"]
                for row in connection.execute(
                    "PRAGMA table_info(visitors)"
                ).fetchall()
            }

            if "qr_token" not in columns:
                connection.execute(
                    "ALTER TABLE visitors ADD COLUMN qr_token TEXT"
                )

            connection.execute("""
                CREATE TABLE IF NOT EXISTS attendance (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    visitor_id INTEGER NOT NULL,
                    check_in TEXT DEFAULT CURRENT_TIMESTAMP,
                    check_out TEXT,
                    FOREIGN KEY (visitor_id) REFERENCES visitors(id)
                )
            """)

        # Generate QR tokens for existing visitors that need them.
        visitors = connection.execute(
            "SELECT id, qr_token FROM visitors"
        ).fetchall()

        for visitor in visitors:
            token = visitor["qr_token"]

            if not token:
                token = secrets.token_urlsafe(32)

                db_execute(
                    connection,
                    "UPDATE visitors SET qr_token = ? WHERE id = ?",
                    (token, visitor["id"]),
                )

            create_qr_for_visitor(visitor["id"], token)

        connection.commit()

    except Exception:
        connection.rollback()
        app.logger.exception("Database initialization failed")
        raise

    finally:
        connection.close()

