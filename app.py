@app.route("/")
def dashboard():
    connection = get_db_connection()

    try:
        total_visitors = connection.execute(
            "SELECT COUNT(*) AS total FROM visitors"
        ).fetchone()["total"]

        inside_count = connection.execute("""
            SELECT COUNT(*) AS total
            FROM attendance
            WHERE check_out IS NULL
        """).fetchone()["total"]

        attendance_count = connection.execute(
            "SELECT COUNT(*) AS total FROM attendance"
        ).fetchone()["total"]

        recent_records = connection.execute("""
            SELECT attendance.id,
                   attendance.visitor_id,
                   attendance.check_in,
                   attendance.check_out,
                   visitors.full_name,
                   visitors.purpose
            FROM attendance
            JOIN visitors ON visitors.id = attendance.visitor_id
            ORDER BY attendance.id DESC
            LIMIT 6
        """).fetchall()

        # PostgreSQL query para sa Render
        if DATABASE_URL:
            raw_chart = connection.execute("""
                SELECT check_in::date AS visit_date,
                       COUNT(*) AS total
                FROM attendance
                WHERE check_in::date >= CURRENT_DATE - 6
                GROUP BY check_in::date
            """).fetchall()

        # SQLite query para sa local computer
        else:
            raw_chart = connection.execute("""
                SELECT date(check_in) AS visit_date,
                       COUNT(*) AS total
                FROM attendance
                WHERE date(check_in) >= date('now', '-6 days')
                GROUP BY date(check_in)
            """).fetchall()

    finally:
        connection.close()

    count_by_day = {
        (
            row["visit_date"].isoformat()
            if hasattr(row["visit_date"], "isoformat")
            else row["visit_date"]
        ): row["total"]
        for row in raw_chart
        if row["visit_date"]
    }


    chart_data = []

    for offset in range(6, -1, -1):
        day = date.today() - timedelta(days=offset)
        count = count_by_day.get(day.isoformat(), 0)

        chart_data.append({
            "label": day.strftime("%a"),
            "count": count,
            "height":  max(5, round(count / max(
                [count_by_day.get(
                    (date.today() - timedelta(days=i)).isoformat(), 0
                ) for i in range(7)] + [1]
            ) * 100)),
        })

    return render_page(
        DASHBOARD_PAGE,
        "dashboard",
        page_title="Dashboard",
        total_visitors=total_visitors,
        inside_count=inside_count,
        attendance_count=attendance_count,
        recent_records=recent_records,
        chart_data=chart_data,
    )



