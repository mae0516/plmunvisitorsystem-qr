
import os
import sqlite3
import sys

import psycopg
from psycopg import sql


BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SQLITE_DATABASE = os.path.join(BASE_DIR, "plmun.db")


def get_database_url():
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        print("ERROR: DATABASE_URL environment variable is missing.")
        sys.exit(1)

    return database_url


def migrate():
    database_url = get_database_url()

    if not os.path.exists(SQLITE_DATABASE):
        print("ERROR: Local plmun.db was not found.")
        sys.exit(1)

    sqlite_connection = sqlite3.connect(SQLITE_DATABASE)
    sqlite_connection.row_factory = sqlite3.Row

    try:
        visitors = sqlite_connection.execute(
            "SELECT id, full_name, contact_number, purpose, "
            "created_at, qr_token FROM visitors ORDER BY id"
        ).fetchall()

        attendance = sqlite_connection.execute(
            "SELECT id, visitor_id, check_in, check_out "
            "FROM attendance ORDER BY id"
        ).fetchall()

        print(f"Local visitors: {len(visitors)}")
        print(f"Local attendance records: {len(attendance)}")

        with psycopg.connect(database_url) as pg:
            with pg.cursor() as cursor:
                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS visitors (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        full_name TEXT NOT NULL,
                        contact_number TEXT NOT NULL,
                        purpose TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        qr_token TEXT
                    )
                """)

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS attendance (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        visitor_id INTEGER NOT NULL REFERENCES visitors(id),
                        check_in TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        check_out TIMESTAMP
                    )
                """)

                cursor.execute("SELECT COUNT(*) FROM visitors")
                existing_visitors = cursor.fetchone()[0]

                cursor.execute("SELECT COUNT(*) FROM attendance")
                existing_attendance = cursor.fetchone()[0]

                if existing_visitors or existing_attendance:
                    print(
                        "STOP: PostgreSQL already contains records. "
                        "No records were copied."
                    )
                    return

                for visitor in visitors:
                    cursor.execute("""
                        INSERT INTO visitors
                            (id, full_name, contact_number, purpose,
                             created_at, qr_token)
                        VALUES (%s, %s, %s, %s, %s, %s)
                    """, (
                        visitor["id"],
                        visitor["full_name"],
                        visitor["contact_number"],
                        visitor["purpose"],
                        visitor["created_at"],
                        visitor["qr_token"],
                    ))

                for record in attendance:
                    cursor.execute("""
                        INSERT INTO attendance
                            (id, visitor_id, check_in, check_out)
                        VALUES (%s, %s, %s, %s)
                    """, (
                        record["id"],
                        record["visitor_id"],
                        record["check_in"],
                        record["check_out"],
                    ))

                cursor.execute("""
                    SELECT setval(
                        pg_get_serial_sequence('visitors', 'id'),
                        COALESCE((SELECT MAX(id) FROM visitors), 1),
                        EXISTS (SELECT 1 FROM visitors)
                    )
                """)

                cursor.execute("""
                    SELECT setval(
                        pg_get_serial_sequence('attendance', 'id'),
                        COALESCE((SELECT MAX(id) FROM attendance), 1),
                        EXISTS (SELECT 1 FROM attendance)
                    )
                """)

                cursor.execute("SELECT COUNT(*) FROM visitors")
                migrated_visitors = cursor.fetchone()[0]

                cursor.execute("SELECT COUNT(*) FROM attendance")
                migrated_attendance = cursor.fetchone()[0]

                if (migrated_visitors != len(visitors)
                        or migrated_attendance != len(attendance)):
                    raise RuntimeError(
                        "Record count verification failed; rolling back."
                    )

            print("Migration successful.")
            print(f"Verified visitors: {migrated_visitors}")
            print(f"Verified attendance: {migrated_attendance}")

    finally:
        sqlite_connection.close()


if __name__ == "__main__":
    migrate()